import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const code=fs.readFileSync(new URL('../price-history.js',import.meta.url),'utf8');
const context={window:{},document:{readyState:'loading',addEventListener(){},getElementById(){return null;},createElement(){return{style:{}};},body:{}},MutationObserver:class{observe(){}},requestAnimationFrame(fn){fn();},console};
context.window.window=context.window;context.window.document=context.document;context.window.addEventListener=()=>{};
vm.createContext(context);vm.runInContext(code,context,{filename:'price-history.js'});
const api=context.window.TDPriceHistory;
assert(api,'TDPriceHistory must be exposed');
assert.equal(api.median([100,120,110]),110);
let r=api.analyse({prices:[130,128,126,124,100],current:100,claimedDiscountPct:35,verified:true});
assert.equal(r.state,'inflated_claim');
assert.equal(r.baseline,127);
assert.equal(r.realDiscountPct,21);
assert.equal(r.fakeGapPct,14);
r=api.analyse({prices:[120,118,116,114,100],current:100,claimedDiscountPct:15,verified:true});
assert.equal(r.state,'good_price');
r=api.analyse({prices:[100,101,99],current:90,claimedDiscountPct:20,verified:true});
assert.equal(r.state,'unknown');
console.log('Price history tests passed: median baseline, real discount, anti-fake gap and minimum history gate.');
